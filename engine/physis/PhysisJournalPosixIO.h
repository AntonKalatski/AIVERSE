// PHYSIS: testable POSIX receipt journal I/O bound to an owned directory fd.
// No ECS, editor, genre, transport, or serialization dependencies.
// Caller must hold the journal process lock for the entire operation.
#pragma once
#ifndef _WIN32
#include <cerrno>
#include <cstddef>
#include <cstdio>
#include <cstdint>
#include <fcntl.h>
#include <string>
#include <sys/stat.h>
#include <unistd.h>
#include <utility>
#include <vector>

namespace aiverse::physis::remote::posix_journal {

inline bool validBasename(const std::string& name) {
    return !name.empty() && name!="." && name!=".." &&
           name.find('/')==std::string::npos &&
           name.find('\\0')==std::string::npos;
}
inline bool error(std::string* out,const char* message) {
    if(out)*out=message;
    return false;
}
inline bool ownedDirectory(int fd) {
    struct stat state{};
    return fd>=0 && ::fstat(fd,&state)==0 &&
           S_ISDIR(state.st_mode) && state.st_uid==::geteuid() &&
           (state.st_mode & 0022)==0;
}

// Missing file means an empty, not-yet-created journal; an unsafe existing
// path is never treated as missing. Output is unchanged on read failure.
inline bool read(int directory,const std::string& name,
                 std::size_t minBytes,std::size_t maxBytes,
                 std::vector<std::uint8_t>& output,bool& missing,
                 std::string* why=nullptr) {
    missing=false;
    if(!ownedDirectory(directory) || !validBasename(name))
        return error(why,"PHYSIS pinned journal directory or name invalid");
    int flags=O_RDONLY|O_NONBLOCK;
#ifdef O_CLOEXEC
    flags|=O_CLOEXEC;
#endif
#ifdef O_NOFOLLOW
    flags|=O_NOFOLLOW;
#endif
    const int fd=::openat(directory,name.c_str(),flags);
    if(fd<0) {
        if(errno==ENOENT) {
            missing=true;
            if(why)why->clear();
            return true;
        }
        return error(why,"PHYSIS pinned journal cannot be opened safely");
    }
    struct stat state{};
    const bool safe=::fstat(fd,&state)==0 &&
        S_ISREG(state.st_mode) && state.st_nlink==1 &&
        state.st_uid==::geteuid() && (state.st_mode & 0077)==0 &&
        state.st_size>=0 &&
        static_cast<std::uint64_t>(state.st_size)>=minBytes &&
        static_cast<std::uint64_t>(state.st_size)<=maxBytes;
    if(!safe) {
        ::close(fd);
        return error(why,"PHYSIS pinned journal inode or size invalid");
    }
    std::vector<std::uint8_t> candidate(static_cast<std::size_t>(state.st_size));
    std::size_t offset=0;
    bool good=true;
    while(offset<candidate.size()) {
        const auto count=::read(fd,candidate.data()+offset,candidate.size()-offset);
        if(count<0 && errno==EINTR)continue;
        if(count<=0) {good=false;break;}
        offset+=static_cast<std::size_t>(count);
    }
    // The opened fd can outlive its published pathname. Detect a rename,
    // replacement or size mutation during the read before exposing bytes
    // as an authoritative journal checkpoint.
    struct stat finalFd{}, visible{};
    if(good)good=::fstat(fd,&finalFd)==0 &&
        ::fstatat(directory,name.c_str(),&visible,AT_SYMLINK_NOFOLLOW)==0 &&
        S_ISREG(visible.st_mode) &&
        finalFd.st_dev==state.st_dev &&
        finalFd.st_ino==state.st_ino &&
        finalFd.st_size==state.st_size &&
        visible.st_dev==state.st_dev &&
        visible.st_ino==state.st_ino &&
        visible.st_nlink==1 &&
        visible.st_uid==::geteuid() &&
        (visible.st_mode & 0077)==0 &&
        ownedDirectory(directory);
    if(::close(fd)!=0)good=false;
    if(!good)return error(why,"PHYSIS pinned journal read or path identity failed");
    output=std::move(candidate);
    if(why)why->clear();
    return true;
}

// The random suffix is generated by the caller's cryptographic OS RNG.
// renameat never follows the final target symlink; fsync(directory)
// makes the directory entry durable on supporting local filesystems.
inline bool write(int directory,const std::string& name,
                  const std::vector<std::uint8_t>& bytes,
                  const std::string& randomSuffix,
                  std::string* why=nullptr) {
    if(!ownedDirectory(directory) || !validBasename(name) ||
       randomSuffix.empty() || randomSuffix.find('/')!=std::string::npos ||
       randomSuffix.find('\\0')!=std::string::npos)
        return error(why,"PHYSIS pinned journal directory or name invalid");
    const std::string temporary=name+".next-"+randomSuffix;
    int flags=O_WRONLY|O_CREAT|O_EXCL;
#ifdef O_CLOEXEC
    flags|=O_CLOEXEC;
#endif
#ifdef O_NOFOLLOW
    flags|=O_NOFOLLOW;
#endif
    const int fd=::openat(directory,temporary.c_str(),flags,0600);
    if(fd<0)return error(why,"PHYSIS pinned journal temp creation failed");
    std::size_t offset=0;
    bool good=true;
    while(offset<bytes.size()) {
        const auto count=::write(fd,bytes.data()+offset,bytes.size()-offset);
        if(count<0 && errno==EINTR)continue;
        if(count<=0) {good=false;break;}
        offset+=static_cast<std::size_t>(count);
    }
    if(good && ::fsync(fd)!=0)good=false;
    if(::close(fd)!=0)good=false;
    if(!good) {
        (void)::unlinkat(directory,temporary.c_str(),0);
        return error(why,"PHYSIS pinned journal write/fsync failed");
    }
    if(::renameat(directory,temporary.c_str(),directory,name.c_str())!=0) {
        (void)::unlinkat(directory,temporary.c_str(),0);
        return error(why,"PHYSIS pinned journal rename failed");
    }
    if(::fsync(directory)!=0 || !ownedDirectory(directory))
        return error(why,"PHYSIS pinned journal directory fsync/ownership failed");
    if(why)why->clear();
    return true;
}

} // namespace aiverse::physis::remote::posix_journal
#endif
